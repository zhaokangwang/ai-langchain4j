CREATE TABLE conversations (
    id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(64) NOT NULL,
    title VARCHAR(160) NOT NULL,
    source VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE chat_runs (
    run_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL UNIQUE,
    conversation_id VARCHAR(64) NOT NULL REFERENCES conversations(id),
    input_text CLOB NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('RUNNING','COMPLETED','FAILED','INTERRUPTED')),
    attempt_count INT NOT NULL,
    response_json CLOB,
    context_json CLOB,
    error_type VARCHAR(160),
    created_at BIGINT NOT NULL,
    started_at BIGINT NOT NULL,
    finished_at BIGINT,
    duration_ms BIGINT
);
CREATE INDEX idx_runs_context ON chat_runs(conversation_id, status, run_seq);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL REFERENCES chat_runs(request_id),
    role VARCHAR(20) NOT NULL,
    content CLOB NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (request_id, role)
);

CREATE TABLE model_calls (
    id VARCHAR(64) PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL REFERENCES chat_runs(request_id),
    attempt_no INT NOT NULL,
    round_no INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    request_json CLOB NOT NULL,
    response_json CLOB,
    model_name VARCHAR(200),
    input_tokens INT,
    output_tokens INT,
    total_tokens INT,
    error_type VARCHAR(160),
    started_at BIGINT NOT NULL,
    finished_at BIGINT,
    duration_ms BIGINT
);
CREATE INDEX idx_model_run ON model_calls(request_id, attempt_no, round_no);

CREATE TABLE tool_calls (
    id VARCHAR(64) PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL REFERENCES chat_runs(request_id),
    attempt_no INT NOT NULL,
    round_no INT NOT NULL,
    call_id VARCHAR(200),
    tool_name VARCHAR(100) NOT NULL,
    arguments_json CLOB,
    result_text CLOB,
    status VARCHAR(20) NOT NULL,
    skill_name VARCHAR(100),
    skill_sha256 VARCHAR(64),
    error_type VARCHAR(160),
    started_at BIGINT NOT NULL,
    finished_at BIGINT,
    duration_ms BIGINT
);
CREATE INDEX idx_tool_run ON tool_calls(request_id, attempt_no, started_at);

CREATE TABLE operation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(64) REFERENCES conversations(id),
    request_id VARCHAR(64) REFERENCES chat_runs(request_id),
    event_type VARCHAR(50) NOT NULL,
    details VARCHAR(500),
    created_at BIGINT NOT NULL
);
